/** Langue par défaut de l'interface tant que l'utilisateur n'en a pas choisi une autre. */
export const DEFAULT_LANG: Lang = "en";

/** Langue courante, pour les fonctions appelées hors composant (libellés de statut…). */
let currentLang: Lang = DEFAULT_LANG;

/**
 * Traduction hors composant React (mappers, fonctions de libellés). Les composants
 * appelants se re-rendent déjà au changement de langue via useLang().
 */
export function tr(s: string): string {
  return currentLang === "fr" ? s : EN[s] ?? s;
}

/** Appelé par le LanguageProvider à chaque rendu : langue courante pour tr(). */
export function setCurrentLang(lang: Lang): void {
  currentLang = lang;
}
